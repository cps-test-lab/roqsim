def test_the_renamed_root_link_is_in_the_matrix(collapsed):
    """`--root-link` renames the root body, and the matrix must still cover that link.

    A Menagerie arm's root body is `base`; the URDF calls it `base_link` (or whatever --root-link
    says), so matching bodies to link names by name alone leaves the root unmapped -- and a link absent
    from the matrix is a link MoveIt keeps checking. Root and first link touch at their shared axis in
    every state, so the missing `Adjacent` entry is the expensive kind.
    """
    model, urdf = collapsed
    links = links_from_urdf(model, urdf, strip="ur10e_")
    assert "arm_base_link" in links.values(), "the renamed root link is not in the matrix at all"
    assert links[exported_root_body(model, links)] == "arm_base_link"
    matrix = {(a, b): r for a, b, r in collision_matrix(model, links, samples=50)}
    assert _reason(matrix, "arm_base_link", "shoulder_link") == "Adjacent"


def test_a_mounted_arm_rides_the_base_free_joint(collapsed):
    """The arm is welded to a Husky, and the Husky floats: that is a planar virtual joint."""
    model, urdf = collapsed
    links = links_from_urdf(model, urdf, strip="ur10e_")
    # The free joint belongs to the BASE, which is not part of the exported URDF -- so the walk has to
    # leave the exported subtree to find it.
    assert base_free_joint(model, links) is not None
    assert resolve_base_joint(model, links)[0] == "planar"


def test_a_bolted_down_arm_gets_no_virtual_joint(bolted):
    """The regression this exists for: a pedestal arm must not be handed a virtual joint.

    Nothing publishes odom -> base_link in a static cell, so move_group logs "The complete state of the
    robot is not yet known. Missing virtual_joint" once a second and never assembles a complete robot
    state. It does not fail outright -- a driver that pins start states still gets answers -- it just
    mostly times out. Measured on the Kwee UR5e cell: 7/28 queries solved with the joint, 28/28 without.
    """
    model, urdf = bolted
    links = links_from_urdf(model, urdf, strip="ur5e_")
    assert base_free_joint(model, links) is None
    assert resolve_base_joint(model, links)[0] == "fixed"

    tree = build_srdf(
        model,
        links,
        name="test_arm",
        arm_base="base_link",
        arm_tip="wrist_3_link",
        gripper_joint="robotiq_85_left_knuckle_joint",
        gripper_open=0.0,
        gripper_close=0.8,
        home={},
        samples=50,
    )
    assert tree.getroot().find("virtual_joint") is None


def test_declaring_a_virtual_joint_on_a_bolted_down_arm_is_refused(bolted):
    """Explicitly asking for the broken file must fail, not be honoured quietly.

    Suppressing a virtual joint is only ever a degraded planning frame; declaring one nothing publishes
    breaks the robot state, so the two directions are not symmetric and only one is refused.
    """
    model, urdf = bolted
    links = links_from_urdf(model, urdf, strip="ur5e_")
    for requested in ("planar", "floating"):
        with pytest.raises(ValueError, match="Missing virtual_joint"):
            resolve_base_joint(model, links, requested)


# A rail carriage in miniature: the root body slides, and its child is the arm's first link. Both
# bodies are one tree, as any exported URDF is.
RAIL = """
<mujoco>
  <compiler angle="radian"/>
  <worldbody>
    <body name="carriage">
      <joint name="rail" type="slide" axis="1 0 0" range="0 2"/>
      <geom name="g_carriage" type="box" size="0.1 0.1 0.1" mass="1"/>
      <body name="link_1" pos="0 0 0.2">
        <joint name="j_1" type="hinge" axis="0 0 1"/>
        <geom name="g_1" type="box" size="0.1 0.1 0.1" mass="1"/>
      </body>
    </body>
  </worldbody>
</mujoco>
"""


def _ids(model, *names) -> dict[int, str]:
    return {int(mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, n)): n for n in names}


def test_a_jointed_root_is_not_a_floating_base():
    """A hinge or slide above the root is a real URDF joint, not a base whose pose lives in TF.

    `roqsim export urdf` emits such a root below a synthetic fixed `world` link, so MoveIt already has the
    fixed root it requires. Only a MuJoCo FREE joint means the base's pose comes from TF.
    """
    model = mujoco.MjModel.from_xml_string(RAIL)
    links = _ids(model, "carriage", "link_1")
    assert base_free_joint(model, links) is None
    assert resolve_base_joint(model, links)[0] == "fixed"

    floating = mujoco.MjModel.from_xml_string(
        RAIL.replace('<joint name="rail" type="slide" axis="1 0 0" range="0 2"/>', "<freejoint/>")
    )
    # An unnamed free joint still has to be reported as one, since the verdict hinges on its existence.
    assert base_free_joint(floating, _ids(floating, "carriage", "link_1")) is not None
    assert resolve_base_joint(floating, _ids(floating, "carriage", "link_1"))[0] == "planar"


def test_links_reaching_outside_the_robot_are_rejected():
    """Two roots means `links` covers more than one tree, and every base verdict would be arbitrary.

    It is a real mistake, not a hypothetical: `--strip` that matches too little leaves a URDF link name
    matching a body in some other subtree of the world.
    """
    model = mujoco.MjModel.from_xml_string(CHAIN)
    links = _ids(model, "link_a", "link_b", "link_far")  # link_far is its own tree
    with pytest.raises(ValueError, match="exactly one root link"):
        exported_root_body(model, links)


def test_collapsed_gripper_members_map_to_the_collapsed_link(collapsed):
    """Every body folded into a collapsed link must be ATTRIBUTED to that link in the matrix.

    This is what makes the matrix agree with the URDF rather than with the MJCF. A 2F-85's thirteen
    linkage bodies become one ``base_mount`` link whose ``<collision>`` carries all of their geometry,
    so MoveIt checks *that link* against the wrist — and if the sampler only ever attributed the
    collapse ROOT's own geoms, the finger geometry's verdicts would be missing entirely. Missing means
    "keep checking", so a finger that overlaps the wrist in every state would block every plan, with no
    error anywhere to explain it.
    """
    model, urdf = collapsed
    links = links_from_urdf(model, urdf, strip="ur10e_")
    urdf_links = {link.get("name") for link in ET.parse(urdf).getroot().findall("link")}
    assert "base_mount" in urdf_links
    # The linkage bodies are gone from the URDF...
    assert "robotiq_85_base_link" not in urdf_links
    # ...so their MuJoCo bodies must resolve to the link that swallowed them.
    for body_name in (
        "ur10e_robotiq_85_base_link",
        "ur10e_left_pad",
        "ur10e_right_silicone_pad",
    ):
        bid = int(mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, body_name))
        assert bid > 0, f"{body_name} is not in this model"
        assert links.get(bid) == "base_mount", (
            f"{body_name} maps to {links.get(bid)!r}; its geometry is part of the base_mount link in "
            "the URDF, so its contacts must be attributed there"
        )


def test_bodies_outside_the_robot_are_not_mapped(collapsed):
    """Walking up to a parent link must not drag in the world's own bodies.

    The husky is in this model too and is not part of the exported arm; a mapping that reached for "the
    nearest ancestor with a link" without checking would attribute chassis contacts to the arm.
    """
    model, urdf = collapsed
    links = links_from_urdf(model, urdf, strip="ur10e_")
    for body_name in ("husky_base_link", "husky_front_left_wheel_link"):
        bid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, body_name)
        if bid > 0:
            assert bid not in links, f"{body_name} was mapped to {links.get(bid)!r}"


def test_srdf_declares_the_groups_states_and_virtual_joint(collapsed):
    """The semantic half: what a human chose, spelled the way MoveIt expects to read it."""
    model, urdf = collapsed
    links = links_from_urdf(model, urdf, strip="ur10e_")
    tree = build_srdf(
        model,
        links,
        name="test_robot",
        arm_base="arm_base_link",
        arm_tip="wrist_3_link",
        gripper_joint="robotiq_85_left_knuckle_joint",
        gripper_open=0.0,
        gripper_close=0.8,
        home={"shoulder_pan_joint": 0.0},
        samples=50,
    )
    root = tree.getroot()
    assert root.get("name") == "test_robot"
    # This arm rides a Husky, so the base floats: its pose is TF, not a planning variable. The child
    # link must be the URDF's ROOT (renamed by --root-link) -- srdfdom skips a virtual joint whose
    # child is any other link, which degrades exactly like declaring none.
    vj = root.find("virtual_joint")
    assert vj is not None and vj.get("type") == "planar" and vj.get("parent_frame") == "odom"
    assert vj.get("child_link") == "arm_base_link"
    chain = root.find("group[@name='arm']/chain")
    assert chain.get("base_link") == "arm_base_link" and chain.get("tip_link") == "wrist_3_link"
    ee = root.find("end_effector")
    assert ee.get("group") == "gripper" and ee.get("parent_link") == "wrist_3_link"
    states = {gs.get("name") for gs in root.findall("group_state")}
    assert {"open", "closed", "home"} <= states
    # The gripper's named states must be in the JOINT's units, so a MoveIt named target and a
    # GripperCommand mean the same number.
    closed = root.find("group_state[@name='closed']/joint")
    assert float(closed.get("value")) == pytest.approx(0.8)


def test_srdf_is_parseable_xml(collapsed, tmp_path):
    """Guards the generator's own warning: ElementTree writes `--` inside a comment without complaint,
    and then neither it nor MoveIt can read the file back."""
    model, urdf = collapsed
    links = links_from_urdf(model, urdf, strip="ur10e_")
    out = tmp_path / "robot.srdf"
    build_srdf(
        model,
        links,
        name="test_robot",
        arm_base="arm_base_link",
        arm_tip="wrist_3_link",
        gripper_joint="robotiq_85_left_knuckle_joint",
        gripper_open=0.0,
        gripper_close=0.8,
        home={},
        samples=50,
    ).write(out, encoding="utf-8", xml_declaration=True)
    reparsed = ET.parse(out).getroot()  # raises if the comment or any attribute is malformed
    assert reparsed.tag == "robot"


