"""The MoveIt SRDF export: the semantics come from arguments, the collision matrix is computed.

The matrix is the part worth testing. It is generated by sampling random configurations in MuJoCo (the
Setup Assistant's own algorithm), and the consequences of getting it wrong are asymmetric and both bad:

* a **missing** ``Adjacent``/``Always`` entry leaves MoveIt checking a pair that is in collision in every
  reachable state, so every plan is rejected and the arm simply never moves;
* a **wrongly disabled** pair hides a real self-collision.

Neither shows up as an error, which is why these are behavioural tests over a real composed robot rather
than assertions about the file's shape.
"""

from __future__ import annotations

import xml.etree.ElementTree as ET

import mujoco
import pytest

from roqsim.config import load_config_from_dict
from roqsim.engine import Engine
from roqsim.export_srdf import (
    ArmGroup,
    base_free_joint,
    build_srdf,
    collision_matrix,
    exported_root_bodies,
    exported_root_body,
    links_from_urdf,
    resolve_base_joint,
    unmask_self_collision,
)
from roqsim.export_urdf import UrdfExporter

# ---------------------------------------------------------------------------------------------
# A synthetic three-link chain, so each matrix category can be provoked deliberately.
#
#   link_a  at the origin
#   link_b  a metre away, touching nothing
#   link_c  child of b but positioned back ON TOP of link_a
#   link_far  out of reach of everything
#   link_ghost  visual-only geometry, so it cannot collide by construction
#
# So (a,b) and (b,c) are Adjacent, (a,c) is Always (grandparent/grandchild is NOT parent-filtered by
# MuJoCo, so real contacts appear), and everything involving link_far or link_ghost is Never. Joint
# ranges are deliberately tiny (in RADIANS, see the compiler tag): the links must not be able to move
# apart, or these become sometimes-collides. A joint with hi <= lo is treated as unlimited instead.
# ---------------------------------------------------------------------------------------------
CHAIN = """
<mujoco>
  <!-- angle="radian" explicitly: MuJoCo's compiler defaults to DEGREES, so the joint ranges below
       would otherwise be read as +-0.01 deg. That bites silently -- a sampler over a range 57x too
       small never separates anything, and every pair comes back "Always". -->
  <compiler angle="radian"/>
  <worldbody>
    <body name="link_a">
      <joint name="j_a" type="hinge" axis="0 0 1" range="-0.01 0.01"/>
      <geom name="g_a" type="box" size="0.1 0.1 0.1" mass="1"/>
      <body name="link_b" pos="1 0 0">
        <joint name="j_b" type="hinge" axis="0 0 1" range="-0.01 0.01"/>
        <geom name="g_b" type="box" size="0.1 0.1 0.1" mass="1"/>
        <body name="link_c" pos="-0.95 0 0">
          <joint name="j_c" type="hinge" axis="0 0 1" range="-0.01 0.01"/>
          <geom name="g_c" type="box" size="0.1 0.1 0.1" mass="1"/>
        </body>
      </body>
    </body>
    <body name="link_far" pos="8 0 0">
      <geom name="g_far" type="box" size="0.1 0.1 0.1" mass="1"/>
    </body>
    <body name="link_ghost" pos="0 0 0.02">
      <geom name="g_ghost" type="box" size="0.3 0.3 0.3" mass="1" contype="0" conaffinity="0"/>
    </body>
  </worldbody>
</mujoco>
"""


@pytest.fixture(scope="module")
def chain():
    model = mujoco.MjModel.from_xml_string(CHAIN)
    names = ("link_a", "link_b", "link_c", "link_far", "link_ghost")
    links = {int(mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, n)): n for n in names}
    # 200 samples, not the 10000 default: the ranges here are tiny, so the verdicts do not depend on
    # sample count, and the point of the test is the classification rather than statistical confidence.
    matrix = collision_matrix(model, links, samples=200)
    return model, links, {(a, b): reason for a, b, reason in matrix}


def _reason(matrix: dict, a: str, b: str) -> str | None:
    return matrix.get((a, b)) or matrix.get((b, a))


def test_joined_links_are_adjacent(chain):
    """Links sharing a joint always touch at their axis, and no planner can avoid it."""
    _model, _links, matrix = chain
    assert _reason(matrix, "link_a", "link_b") == "Adjacent"
    assert _reason(matrix, "link_b", "link_c") == "Adjacent"


def test_permanently_overlapping_links_are_always(chain):
    """A pair in collision in every sampled state must be disabled, or nothing ever plans.

    link_c is positioned inside link_a and only its grandparent joint can move it, which is not enough
    to separate them. `Always` rather than `Adjacent` because they are not joined to each other.
    """
    _model, _links, matrix = chain
    assert _reason(matrix, "link_a", "link_c") == "Always"


def test_links_that_never_touch_are_never(chain):
    """The category that makes checking affordable, and the one that is a sampling argument."""
    _model, _links, matrix = chain
    for other in ("link_a", "link_b", "link_c"):
        assert _reason(matrix, other, "link_far") == "Never"


def test_visual_only_geometry_can_never_collide(chain):
    """A link carrying no collision geometry lands in Never as a consequence, not a special case.

    link_ghost is a 0.6 m box straddling link_a, so a version of this that ignored contype/conaffinity
    would classify it Always instead.
    """
    _model, _links, matrix = chain
    assert _reason(matrix, "link_a", "link_ghost") == "Never"


def test_a_sometimes_colliding_pair_is_left_for_moveit_to_check():
    """Neither Never nor Always: MoveIt must keep checking it, so it must NOT appear in the matrix.

    A 1 m bar on a hinge sweeping past a small block: measured, it collides in 62 of 400 sampled
    configurations. Disabling that pair would hide a real self-collision; keeping it costs a check.
    """
    model = mujoco.MjModel.from_xml_string(
        """
        <mujoco>
          <compiler angle="radian"/>
          <worldbody>
            <body name="link_a">
              <joint name="j_a" type="hinge" axis="0 0 1" range="-3.14 3.14"/>
              <geom name="g_a" type="box" size="0.5 0.05 0.05" mass="1"/>
            </body>
            <body name="link_b" pos="0.45 0 0">
              <geom name="g_b" type="box" size="0.05 0.05 0.05" mass="1"/>
            </body>
          </worldbody>
        </mujoco>
        """
    )
    links = {
        int(mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, n)): n for n in ("link_a", "link_b")
    }
    matrix = {(a, b): r for a, b, r in collision_matrix(model, links, samples=400)}
    assert _reason(matrix, "link_a", "link_b") is None, (
        "a bar that sweeps through a block in SOME configurations was disabled; that hides a real "
        "self-collision"
    )


def test_matrix_is_computed_even_when_the_model_masks_self_collision():
    """A model that cannot self-collide must still get a real matrix, not one that disables everything.

    Robot models here routinely mask self-collision off on purpose (`contype=2 / conaffinity=1` on every
    collision geom) because the vendor's collision primitives of neighbouring links overlap at rest.
    Under that mask MuJoCo reports no contacts between robot links at all, so a sampler that trusted it
    would mark every pair `Never` and ship an SRDF with MoveIt's self-collision checking switched off
    entirely. Measured on the TIAGo Pro before this was fixed: 0 contacts over 200 poses, 1711 `Never`,
    0 `Always`.

    The question the matrix asks is geometric, so the sampler enables collision itself — and must put the
    model back afterwards, since the caller goes on to simulate with it.
    """
    # EVERY collision geom masked, which is what a real port does: `contype=2 / conaffinity=1` on the
    # whole robot means no two of its geoms can ever collide with each other. The visual-only
    # link_ghost keeps 0/0 and must stay uncollidable.
    masked = CHAIN
    for geom in ("g_a", "g_b", "g_c", "g_far"):
        masked = masked.replace(
            f'<geom name="{geom}" type="box" size="0.1 0.1 0.1" mass="1"/>',
            f'<geom name="{geom}" type="box" size="0.1 0.1 0.1" mass="1" '
            f'contype="2" conaffinity="1"/>',
        )
    names = ("link_a", "link_b", "link_c", "link_far", "link_ghost")

    # As loaded, nothing can collide. This is the state that produced the meaningless matrix.
    model = mujoco.MjModel.from_xml_string(masked)
    links = {int(mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_BODY, n)): n for n in names}
    data = mujoco.MjData(model)
    mujoco.mj_kinematics(model, data)
    mujoco.mj_collision(model, data)
    assert data.ncon == 0, "fixture is wrong: these geoms should be masked apart as loaded"

    # Sampling it must REFUSE rather than return a matrix that disables everything.
    with pytest.raises(ValueError, match="masked apart"):
        collision_matrix(model, links, samples=50)

    # Clearing the mask on the compiled model does NOT work -- MuJoCo fixes what can collide at compile
    # time. Pinned because it is the trap that makes the fix look unnecessary.
    for g in range(model.ngeom):
        model.geom_contype[g] = 1
        model.geom_conaffinity[g] = 1
    mujoco.mj_kinematics(model, data)
    mujoco.mj_collision(model, data)
    assert data.ncon == 0, (
        "clearing the mask post-compile now works; simplify unmask_self_collision"
    )

    # On the SPEC, before compiling, it does.
    spec = mujoco.MjSpec.from_string(masked)
    assert unmask_self_collision(spec) > 0
    unmasked = spec.compile()
    links = {int(mujoco.mj_name2id(unmasked, mujoco.mjtObj.mjOBJ_BODY, n)): n for n in names}
    matrix = {(a, b): r for a, b, r in collision_matrix(unmasked, links, samples=200)}
    assert _reason(matrix, "link_a", "link_c") == "Always"
    # ...and a link that is only visual stays uncollidable, so it is still Never.
    assert _reason(matrix, "link_a", "link_ghost") == "Never"


