@arms
def test_joint_limits_speeds_and_efforts_are_fanucs(name):
    model = _model(name)
    manifest = yaml.safe_load((_model_dir(name) / f"{name}.manifest.yaml").read_text())
    arm = manifest["components"][0]["arm_controller"]
    for joint, (_, axis, lower, upper, velocity, effort), speed in zip(
        JOINTS, URDF[name]["joints"], DATASHEET[name]["speed_deg"], strict=False
    ):
        assert np.allclose(model.joint(joint).range, [lower, upper], atol=1e-6)
        assert np.allclose(model.joint(joint).axis, axis)
        assert np.allclose(model.actuator(joint).forcerange, [-effort, effort])
        assert np.allclose(model.actuator(joint).ctrlrange, [lower, upper], atol=1e-6)
        # FANUC's description and datasheet agree on the speeds; the manifest enforces them.
        assert math.isclose(velocity, math.radians(speed), rel_tol=1e-6)
        assert math.isclose(arm["max_velocity"][joint], math.radians(speed), rel_tol=1e-5)


@arms
def test_masses_and_inertias_are_fanucs(name):
    model = _model(name)
    for link, mass, com, (ixx, iyy, izz, ixy, ixz, iyz) in URDF[name]["links"]:
        body = model.body(link)
        assert math.isclose(body.mass[0], mass, rel_tol=1e-9)
        assert np.allclose(body.ipos, com, atol=1e-9)
        # MuJoCo stores the principal inertia and its frame; rebuild the tensor to compare.
        rot = np.zeros(9)
        mujoco.mju_quat2Mat(rot, body.iquat)
        rot = rot.reshape(3, 3)
        tensor = rot @ np.diag(body.inertia) @ rot.T
        expected = np.array([[ixx, ixy, ixz], [ixy, iyy, iyz], [ixz, iyz, izz]])
        assert np.allclose(tensor, expected, atol=1e-6 * max(1.0, np.abs(expected).max()))


@arms
def test_arm_mass_is_the_datasheets(name):
    total = sum(m for _, m, _, _ in URDF[name]["links"])
    assert math.isclose(float(_model(name).body_mass.sum()), total, rel_tol=1e-9)
    sheet = DATASHEET[name]
    assert abs(total - sheet["mass"]) <= sheet["mass_tol"] * sheet["mass"]


@arms
def test_forward_kinematics_match_fanucs_chain(name):
    model = _model(name)
    data = mujoco.MjData(model)
    rng = np.random.default_rng(7)
    for _ in range(20):
        q = [rng.uniform(lo, hi) for _, _, lo, hi, _, _ in URDF[name]["joints"]]
        data.qpos[:] = q
        mujoco.mj_kinematics(model, data)
        assert np.linalg.norm(data.site("flange").xpos - _urdf_flange(name, q)) < 1e-4


@arms
def test_tool_site_points_out_of_the_flange(name):
    model = _model(name)
    data = mujoco.MjData(model)
    rng = np.random.default_rng(3)
    for _ in range(5):
        data.qpos[:] = [rng.uniform(lo, hi) for _, _, lo, hi, _, _ in URDF[name]["joints"]]
        mujoco.mj_kinematics(model, data)
        out = data.site("flange").xpos - data.body("J6_link").xpos
        z = data.site("tool_site").xmat.reshape(3, 3)[:, 2]
        assert np.allclose(z, out / np.linalg.norm(out), atol=1e-9)
        assert np.allclose(data.site("tool_site").xpos, data.site("flange").xpos)
        assert np.allclose(data.site("tool_site").xmat, data.site("fanuc_flange").xmat)


@arms
def test_reach_is_the_datasheets(name):
    """M-20iD/25: J1 axis to wrist centre; CRX-25iA: J1 axis to flange. Searched, not computed."""
    model = _model(name)
    data = mujoco.MjData(model)
    point = (
        (lambda: data.body("J5_link").xpos)
        if name == "m20id25"
        else (lambda: data.site("flange").xpos)
    )

    def reach(q2: float, q3: float) -> float:
        data.qpos[:] = [0.0, q2, q3, 0.0, 0.0, 0.0]
        mujoco.mj_kinematics(model, data)
        return float(np.hypot(*point()[:2]))

    best, q2, q3 = 0.0, 0.0, 0.0
    for a in np.linspace(0, math.pi, 61):
        for b in np.linspace(-math.pi, math.pi, 121):
            r = reach(a, b)
            if r > best:
                best, q2, q3 = r, a, b
    step = math.radians(3)
    while step > 1e-6:
        moved = False
        for da, db in ((step, 0), (-step, 0), (0, step), (0, -step)):
            r = reach(q2 + da, q3 + db)
            if r > best:
                best, q2, q3, moved = r, q2 + da, q3 + db, True
        if not moved:
            step /= 2
    assert abs(best - DATASHEET[name]["reach"]) < 1e-3


