"""The FANUC M-20iD/25 (``m20id25``) and CRX-25iA (``crx25ia``), against FANUC's own numbers.

Both are generated by ``external/convert/build_fanuc_mjcf.py`` from FANUC's ``fanuc_description``
(``m20_25_18d`` and ``crx30ia``, which FANUC names the official description of the CRX-25iA). Every
constant below is FANUC's, never measured from the model:

- ``URDF``: the expanded ``robot/<id>.urdf.xacro`` at fanuc_description @ fb40c98 (v2.3.0) --
  joint origins, axes, limits, speeds, efforts, link masses, centres of mass and inertias;
- ``DATASHEET``: FANUC Europe MDS-03437-EN "M-20iD/25 (Hollow wrist)" and MDS-04893-EN "CRX-25iA" --
  arm mass, reach, payload, axis speeds.

The kinematics are checked against a chain rebuilt here from the URDF constants alone, which shares
nothing with the MJCF's body tree. The arm checks run through ``spawn_arm`` and the manifest's
``arm_controller``, as a world runs them.
"""

