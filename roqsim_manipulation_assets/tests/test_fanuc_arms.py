@arms
def test_reach_is_the_datasheets(name):
    """M-20iD/25: J1 axis to wrist centre; CRX-25iA: J1 axis to flange. Searched, not computed."""
    model = _model(name)
    data = mujoco.MjData(model)
    point = (
        (lambda: data.body("J5_link").xpos)
        if name == "m20id25"
        else (lambda: data.site("flange").xpos)
    )

    def reach(q2: float, q3: float) -> float:
        data.qpos[:] = [0.0, q2, q3, 0.0, 0.0, 0.0]
        mujoco.mj_kinematics(model, data)
        return float(np.hypot(*point()[:2]))

    best, q2, q3 = 0.0, 0.0, 0.0
    for a in np.linspace(0, math.pi, 61):
        for b in np.linspace(-math.pi, math.pi, 121):
            r = reach(a, b)
            if r > best:
                best, q2, q3 = r, a, b
    step = math.radians(3)
    while step > 1e-6:
        moved = False
        for da, db in ((step, 0), (-step, 0), (0, step), (0, -step)):
            r = reach(q2 + da, q3 + db)
            if r > best:
                best, q2, q3, moved = r, q2 + da, q3 + db, True
        if not moved:
            step /= 2
    assert abs(best - DATASHEET[name]["reach"]) < 1e-3


