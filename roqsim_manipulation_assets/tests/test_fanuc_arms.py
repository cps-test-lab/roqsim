@arms
def test_visual_meshes_keep_the_budget(name):
    """At most 60k triangles and 5 MB per arm, the size of the other vendor-converted arms."""
    meshes = _model_dir(name) / "meshes"
    triangles = sum(
        sum(1 for line in p.read_text().splitlines() if line.startswith("f "))
        for p in meshes.glob("*_visual_*.obj")
    )
    size = sum(p.stat().st_size for p in meshes.iterdir())
    assert triangles <= 60_000
    assert size <= 5 * 1024 * 1024


#: The forearm lettering's colours in FANUC's J4 COLLADA: a red word mark and dark text, each one
#: flat material piece ("FANUC Robot M-20" / "FANUC Robot CRX-30iA").
LETTERING = {
    "m20id25": [(0.898, 0.0, 0.0), (0.149, 0.149, 0.149)],
    "crx25ia": [(1.0, 0.0, 0.0), (0.102, 0.102, 0.102)],
}


@arms
def test_the_forearm_lettering_is_left_out(name):
    """Apache-2.0 grants no trademark right, and on the CRX-25iA the text would name the 30iA."""
    model = _model(name)
    for i in range(model.ngeom):
        if model.geom_bodyid[i] != model.body("J4_link").id or model.geom_group[i] != 2:
            continue
        rgb = tuple(float(c) for c in model.mat_rgba[model.geom_matid[i]][:3])
        mesh = model.geom_dataid[i]
        start, count = model.mesh_vertadr[mesh], model.mesh_vertnum[mesh]
        flat = np.ptp(model.mesh_vert[start : start + count], axis=0).min() < 0.025
        lettering = any(np.allclose(rgb, c, atol=1e-3) for c in LETTERING[name])
        assert not (flat and lettering), f"{model.mesh(mesh).name} is lettering"


@arms
def test_every_derived_file_names_fanuc_and_its_licence(name):
    folder = _model_dir(name)
    licence = (folder / f"{name.upper()}_LICENSE").read_text()
    assert SOURCE.split(" @ ")[1] in licence
    assert "FANUC America Corporation and FANUC CORPORATION" in licence
    assert "Changes by the roqsim authors" in licence
    assert "Apache License" in licence and "Version 2.0" in licence
    assert "not made or endorsed by FANUC" in licence
    credits = (folder / "CREDITS.txt").read_text()
    assert "Apache-2.0" in credits and "fanuc_description" in credits
    for path in [folder / f"{name}.xml", *sorted((folder / "meshes").glob("*.obj"))]:
        head = "\n".join(path.read_text().splitlines()[:16])
        assert "SPDX-FileCopyrightText: 2025-2026, FANUC America Corporation" in head, path.name
        assert "SPDX-FileCopyrightText: 2025-2026, FANUC CORPORATION" in head, path.name
        assert "SPDX-License-Identifier: Apache-2.0" in head, path.name
        assert re.search(r"Modified by the roqsim authors", head), path.name
