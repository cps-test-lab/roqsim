def _model(name: str) -> mujoco.MjModel:
    asset = resolve_model(f"roqsim_manipulation_assets:{name}")
    spec = mujoco.MjSpec.from_file(str(asset.path))
    apply_assets(spec, asset)
    return spec.compile()


def _model_dir(name: str) -> Path:
    return resolve_model(f"roqsim_manipulation_assets:{name}").path.parent


def _engine(name: str, **arm) -> Engine:
    world = {
        "sim": {"timestep": 0.002},
        "components": [{"spawn_arm": {"model": name, **arm}, "name": "arm"}],
    }
    engine = Engine(load_config_from_dict(world, base_dir=Path(".")), preview=True)
    engine.setup()
    engine.reset()
    return engine


def _rot(axis, angle: float) -> np.ndarray:
    axis = np.asarray(axis, float)
    k = np.array([[0, -axis[2], axis[1]], [axis[2], 0, -axis[0]], [-axis[1], axis[0], 0]])
    return np.eye(3) + math.sin(angle) * k + (1 - math.cos(angle)) * k @ k


def _urdf_flange(name: str, q) -> np.ndarray:
    """The flange position from FANUC's joint origins and axes alone."""
    pos, rot = np.zeros(3), np.eye(3)
    for (origin, axis, *_), angle in zip(URDF[name]["joints"], q, strict=False):
        pos = pos + rot @ np.asarray(origin)
        rot = rot @ _rot(axis, angle)
    return pos + rot @ np.asarray(URDF[name]["flange"])


