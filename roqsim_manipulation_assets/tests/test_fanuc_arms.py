@arms
def test_loads_through_spawn_arm(name):
    engine = _engine(name)
    model = engine.ctx.model
    assert [model.joint(i).name for i in range(model.njnt)] == JOINTS
    assert [model.actuator(i).name for i in range(model.nu)] == JOINTS
    for site in ("wbase", "flange", "fanuc_flange", "tool_site"):
        assert model.site(site).id >= 0


